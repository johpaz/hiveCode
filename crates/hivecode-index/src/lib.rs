//! A project's code index, held in memory and refreshed from disk (port of `agent/source-index.ts`).
//!
//! Paths are relative to the project root, so the same file is the same row from the project or from
//! any of its worktrees. The index is rebuilt lazily: `sync` stats every candidate file and parses
//! only those whose size or mtime moved, so asking again is cheap. Persisting it in HiveDB (the TS
//! version does) comes with the store stage.
//!
//! Imports are read with patterns, not a parser: `import … from`, `export … from`, `require()` and
//! `import()` with a string literal. That covers how real code is written and misses computed
//! specifiers; `relations_complete` is false for file types whose imports are not read at all.
pub mod symbols;

use regex::Regex;
use std::{
    collections::BTreeMap,
    path::{Component, Path, PathBuf},
    sync::LazyLock,
    time::SystemTime,
};
pub use symbols::Symbol;

pub const CODE_EXTENSIONS: &[&str] = &[
    "ts", "tsx", "js", "jsx", "mts", "cts", "mjs", "cjs", "rs", "sql", "json", "toml", "md",
];
const JS_EXTENSIONS: &[&str] = &["ts", "tsx", "js", "jsx", "mts", "cts", "mjs", "cjs"];
const SKIP_DIRS: &[&str] = &[
    "node_modules",
    ".git",
    "dist",
    "build",
    ".next",
    "coverage",
    "target",
    ".aws",
    ".ssh",
    "secrets",
];
const MAX_FILE_BYTES: u64 = 1_000_000;

static GENERATED_NAME: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"(?i)(?:\.generated\.[a-z]+|\.min\.(?:js|css)|\.d\.ts\.map|[-.]lock\.json|(?:^|/)bun\.lockb?)$").unwrap()
});
static GENERATED_HEADER: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r"(?im)^(?:\s*(?://|/\*+|#|--)\s*)(?:@generated|auto-?generated|generated by|do not edit)",
    )
    .unwrap()
});
static SECRET_FILE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?i)^(?:credentials|secrets)\.(?:json|toml)$").unwrap());
static LOCKFILE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?:lock|lockfile)\.(?:json|toml)$").unwrap());
static SPECIFIER: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r#"(?m)(?:\bfrom\s*|\brequire\s*\(\s*|\bimport\s*\(\s*|^\s*import\s+)['"]([^'"\n]+)['"]"#,
    )
    .unwrap()
});
static EXPORT_NAME: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"(?m)^export\s+(?:default\s+)?(?:declare\s+)?(?:async\s+)?(?:abstract\s+)?(?:function\*?|class|interface|type|enum|const|let|var)\s+(\w+)").unwrap()
});
static TEST_FILE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"(?i)(?:\.(?:test|spec)\.[a-z]+$|(?:^|[\\/])(?:tests?|__tests__)[\\/])").unwrap()
});

pub fn is_generated(path: &str, head: Option<&str>) -> bool {
    GENERATED_NAME.is_match(path)
        || head.is_some_and(|h| {
            let end = h.char_indices().nth(400).map_or(h.len(), |(i, _)| i);
            GENERATED_HEADER.is_match(&h[..end])
        })
}

/// Whether a project-relative path is worth indexing.
pub fn should_index(relative: &str) -> bool {
    let path = Path::new(relative);
    let skipped = path.components().any(|c| match c {
        Component::Normal(part) => {
            let part = part.to_string_lossy();
            SKIP_DIRS.contains(&part.as_ref()) || part.starts_with(".env") || part == "secrets"
        }
        _ => true,
    });
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    let ext = path
        .extension()
        .map(|e| e.to_string_lossy().into_owned())
        .unwrap_or_default();
    !skipped
        && !SECRET_FILE.is_match(&name)
        && CODE_EXTENSIONS.contains(&ext.as_str())
        && !LOCKFILE.is_match(relative)
        && !is_generated(relative, None)
}

#[derive(Debug, Clone)]
pub struct FileEntry {
    /// Relative to the project root, `/`-separated.
    pub path: String,
    pub imports: Vec<String>,
    pub imported_by: Vec<String>,
    pub exports: Vec<String>,
    pub symbols: Vec<Symbol>,
    /// False for file types whose imports are not read.
    pub relations_complete: bool,
    modified: Option<SystemTime>,
    size: u64,
}

pub struct Index {
    root: PathBuf,
    files: BTreeMap<String, FileEntry>,
}

fn to_slash(path: &Path) -> String {
    path.components()
        .filter_map(|c| match c {
            Component::Normal(p) => Some(p.to_string_lossy().into_owned()),
            _ => None,
        })
        .collect::<Vec<_>>()
        .join("/")
}

/// Lexical normalisation: `a/b/../c` becomes `a/c`; leaving the root yields None.
fn normalise(path: &Path) -> Option<PathBuf> {
    let mut out = PathBuf::new();
    for c in path.components() {
        match c {
            Component::ParentDir => {
                if !out.pop() {
                    return None;
                }
            }
            Component::Normal(p) => out.push(p),
            _ => {}
        }
    }
    Some(out)
}

impl Index {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self {
            root: root.into(),
            files: BTreeMap::new(),
        }
    }

    /// Re-reads from disk what changed since the last call. Returns how many files were parsed.
    pub fn sync(&mut self) -> usize {
        let mut seen = BTreeMap::new();
        let mut stack = vec![self.root.clone()];
        while let Some(dir) = stack.pop() {
            let Ok(entries) = std::fs::read_dir(&dir) else {
                continue;
            };
            for entry in entries.filter_map(Result::ok) {
                let path = entry.path();
                let Ok(meta) = entry.metadata() else { continue };
                let Ok(rel) = path.strip_prefix(&self.root) else {
                    continue;
                };
                let rel = to_slash(rel);
                if meta.is_dir() {
                    let name = entry.file_name().to_string_lossy().into_owned();
                    if !SKIP_DIRS.contains(&name.as_str()) && !name.starts_with(".env") {
                        stack.push(path);
                    }
                } else if meta.is_file() && should_index(&rel) {
                    seen.insert(rel, (meta.modified().ok(), meta.len()));
                }
            }
        }
        self.files.retain(|path, _| seen.contains_key(path));
        let mut parsed = 0;
        for (rel, (modified, size)) in &seen {
            let fresh = self
                .files
                .get(rel)
                .is_some_and(|f| f.modified == *modified && f.size == *size);
            if fresh {
                continue;
            }
            match self.parse(rel, *modified, *size) {
                Some(entry) => {
                    self.files.insert(rel.clone(), entry);
                    parsed += 1;
                }
                None => {
                    self.files.remove(rel);
                }
            }
        }
        self.link(&seen.keys().cloned().collect::<Vec<_>>());
        parsed
    }

    fn parse(&self, rel: &str, modified: Option<SystemTime>, size: u64) -> Option<FileEntry> {
        if size > MAX_FILE_BYTES {
            return None;
        }
        let bytes = std::fs::read(self.root.join(rel)).ok()?;
        if bytes.contains(&0) {
            return None;
        }
        let source = String::from_utf8_lossy(&bytes);
        if is_generated(rel, Some(&source)) {
            return None;
        }
        let ext = Path::new(rel)
            .extension()
            .map(|e| e.to_string_lossy().into_owned())
            .unwrap_or_default();
        let is_js = JS_EXTENSIONS.contains(&ext.as_str());
        let (mut imports, mut exports) = (vec![], vec![]);
        if is_js {
            let dir = Path::new(rel).parent().unwrap_or(Path::new(""));
            for spec in SPECIFIER.captures_iter(&source).map(|c| c[1].to_owned()) {
                if !spec.starts_with('.') {
                    continue;
                }
                let Some(joined) = normalise(&dir.join(&spec)) else {
                    continue;
                };
                let resolved = self.resolve(&to_slash(&joined));
                if !imports.contains(&resolved) {
                    imports.push(resolved);
                }
            }
            exports = EXPORT_NAME
                .captures_iter(&source)
                .map(|c| c[1].to_owned())
                .collect();
        }
        Some(FileEntry {
            path: rel.to_owned(),
            imports,
            imported_by: vec![],
            exports,
            symbols: symbols::extract(&source, &ext),
            relations_complete: is_js,
            modified,
            size,
        })
    }

    /// `./x` to the file it names: the path itself, or with each known extension, or as a folder index.
    fn resolve(&self, base: &str) -> String {
        let exists = |p: &str| self.root.join(p).is_file();
        if exists(base) {
            return base.to_owned();
        }
        for ext in CODE_EXTENSIONS {
            let direct = format!("{base}.{ext}");
            if exists(&direct) {
                return direct;
            }
            let index = format!("{base}/index.{ext}");
            if exists(&index) {
                return index;
            }
        }
        base.to_owned()
    }

    fn link(&mut self, paths: &[String]) {
        let mut reverse: BTreeMap<String, Vec<String>> = BTreeMap::new();
        for path in paths {
            if let Some(file) = self.files.get(path) {
                for target in &file.imports {
                    reverse
                        .entry(target.clone())
                        .or_default()
                        .push(path.clone());
                }
            }
        }
        for (path, file) in &mut self.files {
            let mut importers = reverse.remove(path).unwrap_or_default();
            importers.sort();
            importers.dedup();
            file.imported_by = importers;
        }
    }

    pub fn files(&self) -> impl Iterator<Item = &FileEntry> {
        self.files.values()
    }

    /// A file given as a relative path, an absolute one inside the root, or a unique path suffix.
    pub fn find(&self, target: &str) -> Option<&FileEntry> {
        let wanted = Path::new(target);
        let relative = if wanted.is_absolute() {
            wanted.strip_prefix(&self.root).ok().map(to_slash)?
        } else {
            to_slash(&normalise(wanted)?)
        };
        if let Some(file) = self.files.get(&relative) {
            return Some(file);
        }
        let tails: Vec<&FileEntry> = self
            .files
            .values()
            .filter(|f| f.path.ends_with(&format!("/{relative}")))
            .collect();
        (tails.len() == 1).then(|| tails[0])
    }

    /// True when the file on disk changed after it was indexed (or is gone).
    pub fn is_stale(&self, file: &FileEntry) -> bool {
        match std::fs::metadata(self.root.join(&file.path)) {
            Ok(meta) => meta.modified().ok() != file.modified || meta.len() != file.size,
            Err(_) => true,
        }
    }

    /// Symbols named like `name` (exact, then last segment, then partial), best first.
    pub fn find_symbol<'a>(
        &'a self,
        name: &str,
        kind: Option<&str>,
    ) -> Vec<(&'a FileEntry, &'a Symbol)> {
        let lower = name.to_lowercase();
        let mut hits: Vec<(u8, &FileEntry, &Symbol)> = vec![];
        for file in self.files.values() {
            for symbol in &file.symbols {
                if kind.is_some_and(|k| k != symbol.kind) {
                    continue;
                }
                let full = symbol.name.to_lowercase();
                let leaf = full.rsplit('.').next().unwrap_or(&full).to_owned();
                let rank = if full == lower {
                    0
                } else if leaf == lower {
                    1
                } else if full.contains(&lower) {
                    2
                } else {
                    continue;
                };
                hits.push((rank, file, symbol));
            }
        }
        hits.sort_by(|a, b| {
            a.0.cmp(&b.0)
                .then(b.2.exported.cmp(&a.2.exported))
                .then(a.1.path.cmp(&b.1.path))
        });
        hits.into_iter().map(|(_, f, s)| (f, s)).collect()
    }

    /// The test files that exercise a source file: the ones that import it, plus a sibling named after it.
    pub fn tests_for(&self, file: &FileEntry) -> Vec<String> {
        let stem = |p: &str| {
            let name = p.rsplit('/').next().unwrap_or(p);
            name.rsplit_once('.').map_or(name, |(s, _)| s).to_owned()
        };
        let dir = |p: &str| p.rsplit_once('/').map_or("", |(d, _)| d).to_owned();
        let target_stem = stem(&file.path);
        let mut out: Vec<String> = file
            .imported_by
            .iter()
            .filter(|p| is_test_path(p))
            .cloned()
            .collect();
        for other in self.files.keys() {
            let sibling = is_test_path(other)
                && dir(other) == dir(&file.path)
                && other
                    .rsplit('/')
                    .next()
                    .and_then(|n| n.rsplit_once(".test.").or_else(|| n.rsplit_once(".spec.")))
                    .is_some_and(|(s, _)| s == target_stem);
            if sibling {
                out.push(other.clone());
            }
        }
        out.sort();
        out.dedup();
        out
    }
}

pub fn is_test_path(path: &str) -> bool {
    TEST_FILE.is_match(path)
}
