use hivecode_index::{Index, symbols::extract};

const TS: &str = "import x from './x'

/** Adds. */
export function add(a: number, b: number) {
  const sum = a + b
  return sum
}

// the store
export class Store {
  private items = []
  async load(id: string) {
    if (id) { return 1 }
  }
  get size() {
    return 0
  }
}

export const LIMIT = 10
type Id = string";

#[test]
fn top_level_declarations_only_never_a_local_const() {
    let symbols = extract(TS, "ts");
    let names: Vec<&str> = symbols.iter().map(|s| s.name.as_str()).collect();
    assert_eq!(
        names,
        ["add", "Store", "Store.load", "Store.size", "LIMIT", "Id"]
    );
}

#[test]
fn ranges_stop_before_the_next_sibling_and_drop_trailing_comments() {
    let symbols = extract(TS, "ts");
    let range = |n: &str| {
        let s = symbols.iter().find(|s| s.name == n).unwrap();
        (s.start_line, s.end_line)
    };
    assert_eq!(range("add"), (4, 7));
    assert_eq!(range("Store"), (10, 18));
    assert_eq!(range("Store.load"), (12, 14));
}

#[test]
fn exported_and_signature_are_kept_and_control_flow_is_not_a_method() {
    let symbols = extract(TS, "ts");
    let add = symbols.iter().find(|s| s.name == "add").unwrap();
    assert!(add.exported);
    assert_eq!(add.signature, "export function add(a: number, b: number)");
    assert!(!symbols.iter().find(|s| s.name == "Id").unwrap().exported);
    assert!(!symbols.iter().any(|s| s.name == "Store.if"));
}

#[test]
fn rust_items_at_the_top_level() {
    let rs =
        "pub struct Office {}\n\nimpl Office {\n    pub fn run(&self) {}\n}\npub fn render() {\n}";
    let got: Vec<String> = extract(rs, "rs")
        .iter()
        .map(|s| format!("{}:{}", s.kind, s.name))
        .collect();
    assert_eq!(got, ["struct:Office", "impl:Office", "fn:render"]);
}

fn project(files: &[(&str, &str)]) -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    for (path, content) in files {
        let full = dir.path().join(path);
        std::fs::create_dir_all(full.parent().unwrap()).unwrap();
        std::fs::write(full, content).unwrap();
    }
    dir
}

#[test]
fn imports_are_resolved_to_files_and_reversed_into_dependents_and_tests() {
    let dir = project(&[
        ("src/store.ts", "export class Store {}\n"),
        ("src/util/index.ts", "export const u = 1\n"),
        (
            "src/app.ts",
            "import { Store } from './store'\nimport { u } from \"./util\"\nconst z = require('../lib/z')\nimport fs from 'node:fs'\n",
        ),
        ("lib/z.js", "module.exports = 1\n"),
        ("src/store.test.ts", "import { Store } from './store'\n"),
        (
            "tests/other.test.ts",
            "import { Store } from '../src/store'\n",
        ),
        ("src/orphan.test.ts", "// nothing\n"),
    ]);
    let mut index = Index::new(dir.path());
    assert_eq!(index.sync(), 7);
    assert_eq!(index.sync(), 0, "nothing changed, nothing re-parsed");

    let app = index.find("src/app.ts").unwrap();
    assert_eq!(
        app.imports,
        ["src/store.ts", "src/util/index.ts", "lib/z.js"],
        "relative only; `node:fs` is external"
    );
    let store = index.find("src/store.ts").unwrap();
    assert_eq!(
        store.imported_by,
        ["src/app.ts", "src/store.test.ts", "tests/other.test.ts"]
    );
    assert_eq!(
        index.tests_for(store),
        ["src/store.test.ts", "tests/other.test.ts"]
    );
    assert_eq!(
        index.tests_for(index.find("src/orphan.test.ts").unwrap()),
        Vec::<String>::new()
    );
    // A unique suffix finds a file, an ambiguous one does not.
    assert_eq!(index.find("store.ts").unwrap().path, "src/store.ts");
    assert!(index.find("nope.ts").is_none());
    assert!(index.find("../etc/passwd").is_none());
}

#[test]
fn what_is_not_the_projects_own_code_is_not_indexed() {
    let dir = project(&[
        ("src/a.ts", "export const a = 1\n"),
        ("node_modules/dep/index.js", "x"),
        ("secrets/key.json", "{}"),
        ("credentials.json", "{}"),
        (".env.local", "K=1"),
        ("src/bundle.generated.ts", "x"),
        (
            "src/auto.ts",
            "// @generated by a tool\nexport const b = 1\n",
        ),
        ("package-lock.json", "{}"),
        ("src/binary.ts", "a\0b"),
        ("README.txt", "x"),
    ]);
    let mut index = Index::new(dir.path());
    index.sync();
    let paths: Vec<&str> = index.files().map(|f| f.path.as_str()).collect();
    assert_eq!(paths, ["src/a.ts"]);
}

#[test]
fn find_symbol_ranks_exact_then_leaf_then_partial_and_filters_by_kind() {
    let dir = project(&[
        (
            "a.ts",
            "export class Store {\n  load() {}\n}\nexport function loader() {}\n",
        ),
        ("b.ts", "function load() {}\n"),
    ]);
    let mut index = Index::new(dir.path());
    index.sync();
    let names: Vec<String> = index
        .find_symbol("load", None)
        .iter()
        .map(|(f, s)| format!("{}:{}", f.path, s.name))
        .collect();
    assert_eq!(
        names,
        ["b.ts:load", "a.ts:Store.load", "a.ts:loader"],
        "exact, then method leaf, then partial"
    );
    assert_eq!(index.find_symbol("load", Some("method")).len(), 1);
    assert!(index.find_symbol("zzz", None).is_empty());
}

#[test]
fn an_edited_file_is_flagged_stale_and_a_sync_picks_it_up() {
    let dir = project(&[("a.ts", "export const a = 1\n")]);
    let mut index = Index::new(dir.path());
    index.sync();
    assert!(!index.is_stale(index.find("a.ts").unwrap()));
    std::fs::write(
        dir.path().join("a.ts"),
        "export const a = 1\nexport function nueva() {}\n",
    )
    .unwrap();
    assert!(
        index.is_stale(index.find("a.ts").unwrap()),
        "edited since it was indexed"
    );
    assert_eq!(index.sync(), 1);
    assert!(index.find_symbol("nueva", None).len() == 1);
    std::fs::remove_file(dir.path().join("a.ts")).unwrap();
    index.sync();
    assert!(
        index.find("a.ts").is_none(),
        "a deleted file leaves the index"
    );
}
