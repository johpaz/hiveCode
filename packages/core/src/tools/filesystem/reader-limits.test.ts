import { afterAll, beforeAll, describe, expect, test } from "bun:test"
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { fsReadTool } from "./fs-read.ts"
import { searchInFilesTool } from "./search-in-files.ts"
import { renderToolResult } from "../../utils/tool-render.ts"
import { isGeneratedFile } from "../../agent/source-index.ts"
import { isReaderAgent } from "../../agent/loadout.ts"

let dir = ""
const as = (agent_id: string) => ({ configurable: { workspace: dir, agent_id } })

beforeAll(() => {
  dir = mkdtempSync(path.join(tmpdir(), "reader-limits-"))
  mkdirSync(path.join(dir, "src"))
  // 300 lines, 7 functions: bigger than a reader's first read, smaller than a writer's.
  const body = Array.from({ length: 300 }, (_, i) => (i % 40 === 0 ? `export function fn${i / 40}() {` : `  const v${i} = ${i}`)).join("\n")
  writeFileSync(path.join(dir, "src/big.ts"), body)
  writeFileSync(path.join(dir, "src/many.ts"), Array.from({ length: 80 }, (_, i) => `const needle${i} = "${"x".repeat(400)}"`).join("\n"))
  writeFileSync(path.join(dir, "src/data.generated.ts"), "export const needle = 1\n")
})
afterAll(() => rmSync(dir, { recursive: true, force: true }))

describe("fs_read", () => {
  test("a reader gets the start of a big file and its structure, a writer the whole of it", async () => {
    const reader = await fsReadTool.execute({ path: "src/big.ts" }, as("scout")) as any
    expect(reader.linesRead).toBe(120)
    expect(reader.structure.length).toBeGreaterThan(3)
    expect(reader.structure[1]).toMatch(/^\d+-\d+ function /)
    expect(reader.note).toContain("por rango")
    const writer = await fsReadTool.execute({ path: "src/big.ts" }, as("builder")) as any
    expect(writer.linesRead).toBe(300)
    expect(writer.structure).toBeUndefined()
  })

  test("a range is always honoured, for anyone", async () => {
    const ranged = await fsReadTool.execute({ path: "src/big.ts", offset: 130, limit: 20 }, as("scout#2")) as any
    expect(ranged.linesRead).toBe(20)
    expect(ranged.structure).toBeUndefined()
  })

  test("the structure reaches the model as text", async () => {
    const text = renderToolResult("fs_read", await fsReadTool.execute({ path: "src/big.ts" }, as("scout")) as any)!
    expect(text).toContain("Estructura del archivo:")
    expect(text).toContain("function export function fn1()")
  })
})

describe("search_in_files", () => {
  test("a reader gets thirty matches with long lines clipped, a writer all of them", async () => {
    const reader = await searchInFilesTool.execute({ pattern: "needle", path: "src" }, as("planner")) as any
    expect(reader.count).toBe(30)
    expect(reader.truncated).toBe(true)
    expect(reader.matches.every((m: any) => m.content.length <= 241)).toBe(true)
    const writer = await searchInFilesTool.execute({ pattern: "needle", path: "src" }, as("builder")) as any
    expect(writer.count).toBeGreaterThan(30)
  })

  test("generated files are not searched", async () => {
    const result = await searchInFilesTool.execute({ pattern: "needle = 1", path: "src" }, as("builder")) as any
    expect(result.matches.some((m: any) => m.file.endsWith("data.generated.ts"))).toBe(false)
  })
})

describe("helpers", () => {
  test("who is a reader", () => {
    for (const id of ["scout", "scout#3", "planner", "planner#2"]) expect(isReaderAgent(id)).toBe(true)
    for (const id of ["bee", "builder", "builder#2", "verifier", "spawn-ab12", undefined, null]) expect(isReaderAgent(id as any)).toBe(false)
  })

  test("what is generated", () => {
    expect(isGeneratedFile("packages/skills/src/bundled-data.generated.ts")).toBe(true)
    expect(isGeneratedFile("dist/app.min.js")).toBe(true)
    expect(isGeneratedFile("src/real.ts")).toBe(false)
    expect(isGeneratedFile("src/x.ts", "// AUTO-GENERATED by tool\nexport const a = 1")).toBe(true)
    expect(isGeneratedFile("src/x.ts", "/** Hand-written. */\nexport const a = 1")).toBe(false)
    expect(isGeneratedFile("src/x.ts", "export const comment = '// do not edit later'")).toBe(false)
  })
})
